#!/usr/bin/env python3
"""Build the application icon files from assets/icon.png.

assets/icon.ico      the Windows executable icon (eidos.rc), 16 to 256 px
engine/platform/icon_rgba.h
                     a 64x64 RGBA copy for SDL_SetWindowIcon (every platform)

Run after changing assets/icon.png:  python tools/mkicon.py
Needs Pillow.
"""

import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "icon.png")
ICO = os.path.join(ROOT, "assets", "icon.ico")
HDR = os.path.join(ROOT, "engine", "platform", "icon_rgba.h")
SIDE = 64


def main():
    im = Image.open(SRC).convert("RGBA")
    im.save(ICO, sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
    small = im.resize((SIDE, SIDE), Image.LANCZOS)
    data = small.tobytes()
    lines = [
        "/* Generated by tools/mkicon.py from assets/icon.png; do not edit. */",
        "",
        "#ifndef EIDOS_ICON_RGBA_H",
        "#define EIDOS_ICON_RGBA_H",
        "",
        "#define EIDOS_ICON_SIDE %d" % SIDE,
        "",
        "/* EIDOS_ICON_SIDE x EIDOS_ICON_SIDE pixels, R, G, B, A, row by row. */",
        "static const unsigned char k_eidos_icon_rgba[%d] = {" % len(data),
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(HDR, "w", newline="\n") as f:
        f.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
