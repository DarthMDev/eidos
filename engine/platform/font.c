/* Anything outside printable ASCII: an outlined box, so a character the
 * font lacks is visibly a placeholder rather than silently dropped. */
static const char k_box[] = "#####|#...#|#...#|#...#|#...#|#...#|#####";

/* U+00C0..U+00FF, each as the ASCII letter it is built on ('?' for the
 * two that are not letters with an accent: the multiplication and
 * division signs are 'x' and '/'). */
static const char k_latin1[65] =
    "AAAAAAACEEEEIIII" "DNOOOOOxOUUUUYPs" "aaaaaaaceeeeiiii" "dnooooo/ouuuuypy";

static u8 g_rows[96][EIDOS_FONT_ROWS];
static int g_ready;

static void parse(const char *s, u8 rows[EIDOS_FONT_ROWS])
{
    int r = 0;
    int col = 0;

    memset(rows, 0, EIDOS_FONT_ROWS);
    for (; *s != '\0' && r < EIDOS_FONT_ROWS; s++) {
        if (*s == '|') {
            r++;
            col = 0;
        } else {
            if (*s == '#' && col < EIDOS_FONT_COLS) {
                rows[r] |= (u8)(0x10u >> col);
            }
            col++;
        }
    }
}

const u8 *eidos_font_glyph(u32 ch)
{
    int i;

    if (!g_ready) {
        for (i = 0; i < 95; i++) {
            parse(k_glyphs[i], g_rows[i]);
        }
        parse(k_box, g_rows[95]);
        g_ready = 1;
    }
    if (ch >= 0xC0u && ch <= 0xFFu) {
        /* Latin-1 letters as their base letter, accent dropped: a path
         * with "Telechargements" in it stays readable. */
        ch = (u8)k_latin1[ch - 0xC0u];
    }
    if (ch >= 0x20u && ch <= 0x7Eu) {
        return g_rows[ch - 0x20u];
    }
    return g_rows[95];
}

u32 eidos_utf8_next(const char **s)
{
    const u8 *p = (const u8 *)*s;
    u32 c = p[0];
    int extra;
    int i;

    if (c == 0) {
        return 0;
    }
    if (c < 0x80u) {
        extra = 0;
    } else if ((c & 0xE0u) == 0xC0u) {
        extra = 1;
        c &= 0x1Fu;
    } else if ((c & 0xF0u) == 0xE0u) {
        extra = 2;
        c &= 0x0Fu;
    } else if ((c & 0xF8u) == 0xF0u) {
        extra = 3;
        c &= 0x07u;
    } else {
        *s += 1;                        /* a stray continuation byte */
        return 0xFFFDu;
    }
    for (i = 1; i <= extra; i++) {
        if ((p[i] & 0xC0u) != 0x80u) {
            *s += i;                    /* cut short: one replacement */
            return 0xFFFDu;
        }
        c = (c << 6) | (p[i] & 0x3Fu);
    }
    *s += extra + 1;
    return c;
}
